import type { AnalysisResponse } from '../types';

function scoreColor(score: number): string {
  if (score >= 75) return '#15803d';
  if (score >= 50) return '#b45309';
  return '#dc2626';
}

export function exportHTMLReport(data: AnalysisResponse, jobTitle?: string): void {
  const score = data.match_analysis.overall_score;
  const label = data.match_analysis.score_label;
  const date = new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' });

  const improvementsHTML = data.resume_improvements.map(s =>
    `<div class="suggestion">
      <strong>${s.section}</strong>
      <p><em>Original:</em> ${escapeHtml(s.original_text)}</p>
      <p><em>Suggested:</em> ${escapeHtml(s.suggested_text)}</p>
      <p><em>Reason:</em> ${escapeHtml(s.reason)}</p>
    </div>`
  ).join('');

  const gapsHTML = data.skill_gaps.map(g =>
    `<li><strong>${escapeHtml(g.skill)}</strong> (${g.importance}) — ${escapeHtml(g.reason)}<br><em>Action:</em> ${escapeHtml(g.suggested_action)}</li>`
  ).join('');

  const questionsHTML = data.interview_questions.map((q, i) =>
    `<div class="question">
      <p><strong>Q${i+1} [${q.category} / ${q.difficulty}]:</strong> ${escapeHtml(q.question)}</p>
      <ul>${q.answer_points.map(p => `<li>${escapeHtml(p)}</li>`).join('')}</ul>
    </div>`
  ).join('');

  const matchedHTML = data.match_analysis.matched_requirements.map(m =>
    `<li class="match-yes">✓ ${escapeHtml(m.requirement)} — <em>${escapeHtml(m.resume_evidence || '')}</em></li>`
  ).join('');

  const partialHTML = data.match_analysis.partial_matches.map(m =>
    `<li class="match-partial">◑ ${escapeHtml(m.requirement)} — <em>${escapeHtml(m.resume_evidence || '')}</em></li>`
  ).join('');

  const missingHTML = data.match_analysis.missing_evidence.map(m =>
    `<li class="match-no">✗ ${escapeHtml(m.requirement)}</li>`
  ).join('');

  const html = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8"/>
<meta name="viewport" content="width=device-width, initial-scale=1"/>
<title>HireAI Report — ${jobTitle || 'Resume Analysis'}</title>
<style>
  body{font-family:Inter,system-ui,sans-serif;max-width:900px;margin:40px auto;padding:0 20px;color:#1e293b;line-height:1.6}
  h1{color:#1e40af;border-bottom:3px solid #2563eb;padding-bottom:12px}
  h2{color:#1e3a8a;margin-top:32px;border-left:4px solid #3b82f6;padding-left:12px}
  .score-badge{display:inline-block;padding:16px 32px;border-radius:12px;font-size:48px;font-weight:800;color:${scoreColor(score)};border:3px solid ${scoreColor(score)};margin:16px 0}
  .label{font-size:18px;color:#64748b;margin-bottom:8px}
  .explanation{background:#f8fafc;border:1px solid #e2e8f0;border-radius:8px;padding:16px;margin:16px 0}
  .match-yes{color:#15803d} .match-partial{color:#b45309} .match-no{color:#dc2626}
  .suggestion{background:#f0f9ff;border:1px solid #bae6fd;border-radius:8px;padding:16px;margin:12px 0}
  .question{background:#fafafa;border:1px solid #e2e8f0;border-radius:8px;padding:16px;margin:12px 0}
  footer{margin-top:48px;padding-top:16px;border-top:1px solid #e2e8f0;color:#94a3b8;font-size:14px}
  @media print{body{margin:20px}}
</style>
</head>
<body>
<h1>🎯 HireAI Analysis Report</h1>
<p><strong>Generated:</strong> ${date}${jobTitle ? ` | <strong>Role:</strong> ${escapeHtml(jobTitle)}` : ''}</p>
${data.model_used ? `<p><strong>Model:</strong> ${escapeHtml(data.model_used)}</p>` : ''}

<h2>Match Score</h2>
<div class="score-badge">${score}</div><span>/100</span>
<div class="label">${escapeHtml(label)}</div>
<div class="explanation">${escapeHtml(data.match_analysis.score_explanation)}</div>

<h2>Requirement Match Breakdown</h2>
<ul>${matchedHTML}${partialHTML}${missingHTML}</ul>

<h2>Strengths</h2>
<ul>${data.match_analysis.strengths.map(s => `<li>${escapeHtml(s)}</li>`).join('')}</ul>

<h2>ATS Findings</h2>
<p>Readability Score: <strong>${data.ats_analysis.readability_score}/100</strong></p>
<ul>${data.ats_analysis.formatting_warnings.map(w => `<li>⚠ ${escapeHtml(w)}</li>`).join('')}</ul>
<p><em>${escapeHtml(data.ats_analysis.limitations)}</em></p>

<h2>Resume Improvements</h2>
${improvementsHTML || '<p>No specific improvements identified.</p>'}

<h2>Skill Gaps</h2>
<ul>${gapsHTML || '<li>No critical gaps identified.</li>'}</ul>

<h2>Interview Questions</h2>
${questionsHTML || '<p>No questions generated.</p>'}

<footer>
  <p>${escapeHtml(data.disclaimer)}</p>
  <p>Generated by HireAI — AI-Powered Career Guidance Platform | Open-source, MIT License</p>
</footer>
</body></html>`;

  const blob = new Blob([html], { type: 'text/html' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `hireai-report-${Date.now()}.html`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

function escapeHtml(str: string): string {
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

export async function copyToClipboard(text: string): Promise<boolean> {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    // Fallback
    const el = document.createElement('textarea');
    el.value = text;
    el.style.position = 'fixed';
    el.style.opacity = '0';
    document.body.appendChild(el);
    el.focus();
    el.select();
    const ok = document.execCommand('copy');
    document.body.removeChild(el);
    return ok;
  }
}
